def write_questions(labelled_path: Path = OUT_DIR / "labelled_data.jsonl",
                    out_path: Path = OUT_DIR / "questions.jsonl") -> int:
    qs = all_questions(labelled_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w") as f:
        for x in qs:
            f.write(x.model_dump_json() + "\n")
    return len(qs)


