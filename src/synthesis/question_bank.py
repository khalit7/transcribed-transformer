# Every question is written in the speaker vocabulary of the transcripts it is asked of
# (decision 2026-09-03): AppTek calls have `agent`/`customer`, Taskmaster conversations
# `assistant`/`user`, ACI-Bench visits `doctor`/`patient`, SPoRC episodes `host` plus
# diarisation tags. A question is shared across corpora only when its wording already
# applies verbatim (the role-agnostic `spk-` set, phrased in terms of "the speakers").
# `gen-` and the four family questions are AppTek's; `tm-` and `aci-` are their
# Taskmaster and ACI-Bench counterparts, dataset-specific by construction; `hst-` are
# SPoRC host-behaviour questions.
ALL = ["apptek", "taskmaster", "aci_bench", "sporc"]


def q(id, family, text, options, description="", tags=None, datasets=("apptek",)):
    return Question(
        id=id, source="bank", family=family, text=text, description=description,
        options=[{"value": v, "criteria": c} for v, c in options], tags=tags or [],
        dataset_allow_list=list(datasets),
    )


# Taskmaster's assistant/user conversations: the same conduct as the AppTek questions in the
# corpus's own vocabulary. Derived by substitution because the behaviours are identical; the
# derived text is what questions.jsonl records.
TM_WORDS = [(r"\bagent's\b", "assistant's"), (r"\bAgent's\b", "Assistant's"), (r"\bagent\b", "assistant"),
            (r"\bAgent\b", "Assistant"), (r"\bcustomer's\b", "user's"), (r"\bCustomer's\b", "User's"),
            (r"\bcustomer\b", "user"), (r"\bCustomer\b", "User"), (r"\bcall\b", "conversation")]


def _tm(text: str) -> str:
    for pat, rep in TM_WORDS:
        text = re.sub(pat, rep, text)
    return text


def tm_variant(base: Question) -> Question:
    """The Taskmaster counterpart of an AppTek question: id gen-NN-x -> tm-NN-x, vocabulary swapped."""
    return Question(
        id=re.sub(r"^(gen|vul|cmp|eod)-", lambda m: f"tm-{m.group(1)}-" if m.group(1) != "gen" else "tm-", base.id),
        source="bank", family=base.family, text=_tm(base.text), description=_tm(base.description),
        options=[{"value": o.value, "criteria": _tm(o.criteria)} for o in base.options], tags=base.tags,
        dataset_allow_list=["taskmaster"],
    )



